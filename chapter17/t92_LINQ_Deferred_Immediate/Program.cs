using System;
using System.Linq;
using System.Collections.Generic;

class Program
{
    static void Main()
    {
        // Исходный список чисел
        List<int> numbers = new List<int> { 1, 2, 3, 4, 5 };

        // ----------------------------------------------------
        // Часть 1: Отложенное выполнение
        // ----------------------------------------------------
        var query1 = numbers.Where(n => n > 2); // Где тут выполнение?

        numbers.Add(6); // Изменяем исходный список

        Console.Write("Результат 1: ");
        foreach (var x in query1)
        {
            Console.Write(x + " ");
        }
        Console.WriteLine();
        // ЗАДАНИЕ: Что выведет строка выше? 


        // ----------------------------------------------------
        // Часть 2: Немедленное выполнение (Кэширование)
        // ----------------------------------------------------
        var query2 = numbers.Where(n => n % 2 == 0).ToList(); // Применили ToList()

        numbers.Add(8); // Снова изменяем список

        Console.Write("Результат 2: ");
        foreach (var x in query2)
        {
            Console.Write(x + " ");
        }
        Console.WriteLine();
        // ЗАДАНИЕ: Что выведет этот цикл?


        // ----------------------------------------------------
        // Часть 3: Агрегатные функции
        // ----------------------------------------------------
        var countQuery = numbers.Where(n => n < 4); // Создали отложенный запрос

        Console.WriteLine($"Результат 3 (Счет 1): {countQuery.Count()}");
        // ЗАДАНИЕ: Сколько элементов вернет Count()? (Помните, что в списке сейчас: 1, 2, 3, 4, 5, 6, 8)


        numbers.Remove(1); // Удаляем единицу из исходного списка

        Console.WriteLine($"Результат 4 (Счет 2): {countQuery.Count()}");
        // ЗАДАНИЕ: Изменится ли значение при повторном вызове метода Count()?
         }
}
